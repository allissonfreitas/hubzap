const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('hubZap', {
  getAppearance: () => ipcRenderer.invoke('appearance:get'),
  setAppearance: value => ipcRenderer.invoke('appearance:set', value),
  setExtraPanel: value => ipcRenderer.invoke('panel:extra', value),
  outlookStatus: () => ipcRenderer.invoke('outlook:status'),
  outlookConnect: () => ipcRenderer.invoke('outlook:connect'),
  outlookDisconnect: () => ipcRenderer.invoke('outlook:disconnect'),
  outlookList: () => ipcRenderer.invoke('outlook:list'),
  outlookOpen: id => ipcRenderer.invoke('outlook:open', id),
  onOutlookCode: cb => ipcRenderer.on('outlook:code', (_e, data) => cb(data)),
  onOutlookEvents: cb => ipcRenderer.on('outlook:events', (_e, data) => cb(data)),
  onOutlookNotice: cb => ipcRenderer.on('outlook:notice', (_e, data) => cb(data)),
  stickersList: () => ipcRenderer.invoke('stickers:list'),
  stickersImport: input => ipcRenderer.invoke('stickers:import', input),
  stickersSave: input => ipcRenderer.invoke('stickers:save', input),
  stickersUpdate: (id, input) => ipcRenderer.invoke('stickers:update', id, input),
  onStickersChanged: cb => ipcRenderer.on('stickers:changed', (_e, data) => cb(data)),
  stickersAction: (id, action) => ipcRenderer.invoke('stickers:action', id, action),
  selectAccount: (id) => ipcRenderer.send('account:select', id),
  setLayout: (layout) => ipcRenderer.send('layout:set', layout),
  reloadAccount: (id) => ipcRenderer.send('account:reload', id),
  setQuickPanel: (open) => ipcRenderer.send('quick:panel', Boolean(open)),
  setSupportPanel: (open) => ipcRenderer.send('support:panel', Boolean(open)),
  setTicketsPanel: (open) => ipcRenderer.send('tickets:panel', Boolean(open)),
  getPrivacy: () => ipcRenderer.invoke('privacy:get'),
  setPrivacy: (settings) => ipcRenderer.invoke('privacy:set', settings),
  openAfatec: () => ipcRenderer.invoke('external:afatec'),
  getSupportTickets: () => ipcRenderer.invoke('tickets:list'),
  saveSupportTicket: (item) => ipcRenderer.invoke('tickets:save', item),
  setSupportTicketStatus: (id, status) => ipcRenderer.invoke('tickets:status', id, status),
  deleteSupportTicket: (id) => ipcRenderer.invoke('tickets:delete', id),
  getSupportEvents: () => ipcRenderer.invoke('support:list'),
  saveSupportEvent: (item) => ipcRenderer.invoke('support:save', item),
  deleteSupportEvent: (id) => ipcRenderer.invoke('support:delete', id),
  completeSupportEvent: (id) => ipcRenderer.invoke('support:done', id),
  snoozeSupportEvent: (id, minutes) => ipcRenderer.invoke('support:snooze', id, minutes),
  onSupportOpenEvent: (callback) => ipcRenderer.on('support:open-event', (_event, id) => callback(id)),
  onSupportEventDue: (callback) => ipcRenderer.on('support:event-due', (_event, item) => callback(item)),
  getQuickMessages: () => ipcRenderer.invoke('quick:list'),
  saveQuickMessage: (message) => ipcRenderer.invoke('quick:save', message),
  deleteQuickMessage: (id) => ipcRenderer.invoke('quick:delete', id),
  copyText: (text) => ipcRenderer.invoke('clipboard:copy', text),
  getVersion: () => ipcRenderer.invoke('app:version'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  downloadUpdate: () => ipcRenderer.invoke('update:download'),
  openRelease: () => ipcRenderer.invoke('update:open-release'),
  installUpdate: () => ipcRenderer.send('update:install'),
  onUpdateStatus: (callback) => ipcRenderer.on('update:status', (_event, status) => callback(status)),
  onUnread: (callback) => ipcRenderer.on('hub:unread', (_event, counts) => callback(counts)),
  onState: (callback) => ipcRenderer.on('hub:state', (_event, state) => callback(state))
});
